# Installs the Model Builder dev loader into SketchUp's Plugins folder.
# The loader is a few lines that load the extension straight from this git
# checkout, so edits take effect after ModelBuilder.reload or a restart.
#
#   powershell -ExecutionPolicy Bypass -File tools\install-dev-loader.ps1 [-SketchUpVersion 2024] [-Uninstall]
param(
    [string]$SketchUpVersion = "2024",
    [switch]$Uninstall
)
$ErrorActionPreference = "Stop"

$repo = Split-Path -Parent $PSScriptRoot
$src = (Join-Path $repo "hosts\sketchup\src") -replace '\\', '/'
$plugins = Join-Path $env:APPDATA "SketchUp\SketchUp $SketchUpVersion\SketchUp\Plugins"
$loader = Join-Path $plugins "model_builder_dev.rb"

if ($Uninstall) {
    if (Test-Path $loader) { Remove-Item $loader -Confirm:$false; Write-Host "Removed $loader" }
    else { Write-Host "Nothing to remove at $loader" }
    exit 0
}

if (-not (Test-Path $plugins)) { throw "Plugins folder not found: $plugins (is SketchUp $SketchUpVersion installed and started once?)" }
if (-not (Test-Path (Join-Path $repo "hosts\sketchup\src\model_builder.rb"))) { throw "Extension source not found under $src" }

$content = @"
# Model Builder DEV LOADER - not shipped. Generated by tools/install-dev-loader.ps1
# Loads the extension from the git checkout below. Remove this file (or run the
# script with -Uninstall) to stop loading it.
begin
  require '$src/model_builder'
rescue LoadError, StandardError => e
  puts "[ModelBuilder] dev loader failed: #{e.class}: #{e.message}"
  puts '[ModelBuilder] expected source at $src'
end
"@

[System.IO.File]::WriteAllText($loader, $content.Replace("`r`n", "`n"), (New-Object System.Text.UTF8Encoding $false))
Write-Host "Installed dev loader: $loader"
Write-Host "  -> loads $src/model_builder.rb"
Write-Host "Start (or restart) SketchUp. Then: Extensions > Model Builder."
